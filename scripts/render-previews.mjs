import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {chromium} from 'playwright';
import {createServer} from 'vite';

// Real assembled geometry, shared lighting and materials; no photographs or mockups.
const root=fileURLToPath(new URL('../',import.meta.url)),out=path.join(root,'src/previews');
const requested=process.argv.find(arg=>arg.startsWith('--ids='))?.slice(6).split(',');
const server=await createServer({root,server:{host:'127.0.0.1',port:0}});
await server.listen();
let browser;
try{
 browser=await chromium.launch({channel:'chrome',headless:true,args:process.platform==='darwin'?['--enable-webgl','--use-angle=metal']:[]});
 const page=await browser.newPage({viewport:{width:384,height:384},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.route('**/__preview-render',route=>route.fulfill({contentType:'text/html',body:'<html data-theme="dark"><body style="margin:0"><div id="host" style="width:384px;height:384px"></div></body></html>'}));
 await page.goto(server.resolvedUrls.local[0]+'__preview-render');
 const ids=await page.evaluate(async()=>{
  const {createScene}=await import('/src/scene.js'),{BOARD_LIST}=await import('/src/boards.js'),T=await import('/node_modules/three/build/three.module.js');
  window.preview={stage:createScene(document.getElementById('host'),()=>{}),boards:BOARD_LIST,T};
  return BOARD_LIST.map(board=>board.id);
 });
 await fs.mkdir(out,{recursive:true});
 if(requested?.some(id=>!ids.includes(id)))throw new Error('Unknown preview ID');
 const renderIds=requested||ids;
 let total=0;
 for(const id of renderIds){
  await page.evaluate(async id=>{
   const {stage,boards,T}=preview,definition=boards.find(board=>board.id===id);
   // Start at zero, even for devices whose interactive default is separated.
   await stage.setBoard({...definition,start:0});
   preview.state={explode:0,selected:null,isolate:true,xray:false,guides:false,rotate:false,playing:false};
   stage.render(preview.state,0,0);stage.view('perspective',true);
   stage.model.root.updateMatrixWorld(true);stage.camera.updateMatrixWorld(true);
   const min=new T.Vector2(Infinity,Infinity),max=new T.Vector2(-Infinity,-Infinity);
   stage.model.root.traverseVisible(object=>{
    if(!object.isMesh)return;
    if(object.isInstancedMesh)object.computeBoundingBox();else object.geometry.computeBoundingBox();
    const bounds=object.isInstancedMesh?object.boundingBox:object.geometry.boundingBox;
    for(const x of [bounds.min.x,bounds.max.x])for(const y of [bounds.min.y,bounds.max.y])for(const z of [bounds.min.z,bounds.max.z]){
     const point=new T.Vector3(x,y,z).applyMatrix4(object.matrixWorld).project(stage.camera);
     min.min(point);max.max(point);
    }
   });
   const camera=stage.camera,center=min.clone().add(max).multiplyScalar(.5);
   const shift=new T.Vector3().setFromMatrixColumn(camera.matrixWorld,0).multiplyScalar(center.x*(camera.right-camera.left)/(2*camera.zoom));
   shift.addScaledVector(new T.Vector3().setFromMatrixColumn(camera.matrixWorld,1),center.y*(camera.top-camera.bottom)/(2*camera.zoom));
   camera.position.add(shift);stage.controls.target.add(shift);stage.controls.update();
   stage.zoom(1.72/Math.max(max.x-min.x,max.y-min.y));
   stage.renderer.setPixelRatio(2);
  },id);
  for(const theme of ['light','dark']){
   const data=await page.evaluate(theme=>{
    const {stage,state}=preview;stage.setTheme(theme);stage.render(state,0,0);
    const canvas=document.createElement('canvas');canvas.width=canvas.height=192;
    const context=canvas.getContext('2d');context.fillStyle=theme==='dark'?'#14171c':'#efeee9';context.fillRect(0,0,192,192);
    context.imageSmoothingQuality='high';context.drawImage(stage.renderer.domElement,0,0,192,192);
    return canvas.toDataURL('image/webp',.86).split(',')[1];
   },theme);
   const buffer=Buffer.from(data,'base64');total+=buffer.length;await fs.writeFile(path.join(out,`${id}-${theme}.webp`),buffer);
  }
  console.log(`Rendered ${id} · assembled · light + dark`);
 }
 if(errors.length)throw new Error(errors.join('\n'));
 const imports=ids.flatMap(id=>['light','dark'].map(theme=>`import ${id}_${theme} from './${id}-${theme}.webp';`)).join('\n');
 const entries=ids.map(id=>` ${id}:{light:${id}_light,dark:${id}_dark}`).join(',\n');
 await fs.writeFile(path.join(out,'index.js'),`// Generated by npm run render:previews.\n${imports}\nexport default {\n${entries}\n};\n`);
 console.log(`${renderIds.length*2} WebP previews rendered · 192 × 192 · ${Math.round(total/1024)} KiB; manifest includes ${ids.length} devices`);
}finally{await browser?.close();await server.close();}
