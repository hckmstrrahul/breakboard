import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {chromium} from 'playwright';
import {createServer} from 'vite';

// Use the live grid's renderer and square framing, including its materials,
// lighting and default camera. These are final idle views, not placeholders.
const root=fileURLToPath(new URL('../',import.meta.url)),out=path.join(root,'src/grid-previews');
const requested=process.argv.find(arg=>arg.startsWith('--ids='))?.slice(6).split(',');
const sizes=[768,2048],themes=['light','dark'];
const server=await createServer({root,server:{host:'127.0.0.1',port:0}});await server.listen();
let browser;
try{
 browser=await chromium.launch({channel:'chrome',headless:true,args:process.platform==='darwin'?['--enable-webgl','--use-angle=metal']:[]});
 const page=await browser.newPage({viewport:{width:768,height:768},deviceScaleFactor:1}),errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 await page.route('**/__grid-previews',route=>route.fulfill({contentType:'text/html',body:'<!doctype html><html><body></body></html>'}));
 await page.goto(server.resolvedUrls.local[0]+'__grid-previews');
 const ids=await page.evaluate(async()=>{
  const {createCollectionRenderer}=await import('/src/collection-renderer.js'),{BOARD_LIST}=await import('/src/boards.js');
  window.previewEngine=createCollectionRenderer(document.createElement('canvas'),{boards:BOARD_LIST,pixelRatio:1,capacity:2,squareFraming:true});
  previewEngine.resize(2048,2048,1);return BOARD_LIST.map(board=>board.id);
 });
 if(requested?.some(id=>!ids.includes(id)))throw new Error('Unknown grid preview ID');
 await fs.mkdir(out,{recursive:true});let bytes=0;
 for(const id of requested||ids){
  await page.evaluate(async id=>{previewEngine.protect([id]);await previewEngine.load(id);},id);
  for(const theme of themes){
   const images=await page.evaluate(({id,theme,sizes})=>{
    previewEngine.setTheme(theme);previewEngine.render([{id,rect:{x:0,y:0,w:2048,h:2048},explode:0,angle:0}]);
    return sizes.map(size=>{
     const canvas=document.createElement('canvas');canvas.width=canvas.height=size;
     const ctx=canvas.getContext('2d',{alpha:false});ctx.imageSmoothingQuality='high';ctx.drawImage(previewEngine.renderer.domElement,0,0,size,size);
     return canvas.toDataURL('image/webp',.88).split(',')[1];
    });
   },{id,theme,sizes});
   for(let i=0;i<sizes.length;i++){const buffer=Buffer.from(images[i],'base64');bytes+=buffer.length;await fs.writeFile(path.join(out,`${id}-${theme}-${sizes[i]}.webp`),buffer);}
  }
  console.log(`Rendered ${id} · 768 + 2048 px · light + dark`);
 }
 if(errors.length)throw new Error(errors.join('\n'));
 const imports=ids.flatMap(id=>themes.flatMap(theme=>sizes.map(size=>`import ${id}_${theme}_${size} from './${id}-${theme}-${size}.webp';`))).join('\n');
 const entries=ids.map(id=>` ${id}:{${themes.map(theme=>`${theme}:{small:${id}_${theme}_768,large:${id}_${theme}_2048}`).join(',')}}`).join(',\n');
 await fs.writeFile(path.join(out,'index.js'),`// Generated by npm run render:grid-previews.\n${imports}\nexport default {\n${entries}\n};\n`);
 console.log(`${(requested||ids).length*4} grid images · ${(bytes/1024/1024).toFixed(2)} MiB`);
}finally{await browser?.close();await server.close();}
